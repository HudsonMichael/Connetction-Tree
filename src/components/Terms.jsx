// kind: 'terms' | 'privacy'
export function TermsModal({ kind, onClose, version = 'v0.1' }) {
  useEffect(() => { const f = (e) => e.key === 'Escape' && onClose(); window.addEventListener('keydown', f); return () => window.removeEventListener('keydown', f) }, [onClose])
  const t = kind === 'terms'
  return (
    <div className="mback" onClick={onClose}>
      <div className="mbox" role="dialog" aria-modal="true" aria-label={t ? '個資告知與使用條款' : '隱私權政策'} onClick={(e) => e.stopPropagation()}>
        <div className="mnote"><span>草稿 {version}・尚未經法律審閱</span><button type="button" aria-label="關閉" onClick={onClose}>×</button></div>
        <div className="mhead"><h4>{t ? '個資告知與使用條款' : '隱私權政策'}</h4><small>版本 {version}</small></div>
        <div className="mbody">{t ? <TermsText /> : <PrivacyText />}</div>
        <div className="mfoot"><button type="button" className="primary" onClick={onClose}>關閉</button></div>
      </div>
    </div>
  )
}
